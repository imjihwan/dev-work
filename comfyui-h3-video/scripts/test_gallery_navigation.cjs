// Scroll/iframe navigation only: no browser, API, gallery metadata or media access.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'../simple_ui');
const gallery=fs.readFileSync(process.argv[2]||path.join(root,'gallery.html'),'utf8');
const main=fs.readFileSync(process.argv[3]||path.join(root,'index.html'),'utf8');
const childSource=gallery.slice(gallery.indexOf('// Gallery menu follows scroll direction.'),gallery.indexOf('// End gallery navigation.'));
assert(childSource.includes('function onGalleryScroll()'));
let clock=1000;
const messages=[],nodes={viewer:{open:false},regenerationDialog:{open:false}};
const win={scrollY:0,innerHeight:700};
const parent={postMessage:(data,origin)=>messages.push({data,origin})};
const child=vm.createContext({window:win,parent,location:{origin:'http://synthetic.local'},document:{hidden:false,documentElement:{scrollHeight:3000}},G:{active:true},$:id=>nodes[id],Date:{now:()=>clock}});
vm.runInContext(childSource,child);
const scroll=(y,elapsed=200)=>{clock+=elapsed;win.scrollY=y;child.onGalleryScroll();};
const hidden=()=>messages.at(-1)?.data.hidden;
scroll(8);scroll(20);assert.equal(messages.length,0,'Do not hide navigation at the top');
scroll(60);assert.equal(hidden(),true);assert.equal(messages[0].origin,'http://synthetic.local');
scroll(100);assert.equal(messages.length,1,'Downward scrolling sends only a state change');
scroll(96);assert.equal(messages.length,1,'Ignore tiny upward jitter');
scroll(84);assert.equal(hidden(),false,'A short upward gesture reveals the menu away from the top');
scroll(90);assert.equal(hidden(),false,'Do not immediately hide again on tiny downward jitter');
scroll(110);assert.equal(hidden(),true);
child.acknowledgeGalleryNavigation(true);const count=messages.length;
scroll(100,20);assert.equal(messages.length,count,'Viewport resize acknowledgement must suppress phantom upward motion');
scroll(80,200);assert.equal(hidden(),false);
scroll(140);assert.equal(hidden(),true);
scroll(-30,20);assert.equal(hidden(),false,'Returning to the top reveals navigation even during suppression');
scroll(2000);scroll(2300);assert.equal(hidden(),true);
const bottomCount=messages.length;
scroll(2450);scroll(2350);scroll(2300);assert.equal(messages.length,bottomCount,'Bottom rubber-band motion must not reveal the menu');
scroll(2280);assert.equal(hidden(),false);
nodes.viewer.open=true;const viewerCount=messages.length;scroll(2400);assert.equal(messages.length,viewerCount);nodes.viewer.open=false;
nodes.regenerationDialog.open=true;scroll(2000);assert.equal(messages.length,viewerCount);nodes.regenerationDialog.open=false;
child.G.active=false;scroll(1800);assert.equal(messages.length,viewerCount);child.G.active=true;
child.document.hidden=true;scroll(1600);assert.equal(messages.length,viewerCount);child.document.hidden=false;

// Parent accepts only boolean navigation messages from its own active gallery iframe.
const classes=new Set(),acks=[];
const body={classList:{contains:v=>classes.has(v),toggle(v,on){if(on)classes.add(v);else classes.delete(v);}}};
const frame={hidden:false,style:{},contentWindow:{postMessage:(data,origin)=>acks.push({data,origin})},getBoundingClientRect:()=>({top:classes.has('gallery-nav-hidden')?0:88})};
const outer=vm.createContext({document:{body},$:id=>{assert.equal(id,'galleryFrame');return frame;},window:{innerHeight:800},location:{origin:'http://synthetic.local'}});
vm.runInContext(main.slice(main.indexOf('function sizeGalleryFrame('),main.indexOf('function selectAppTab(')),outer);
const send=(data,extra={})=>outer.onGalleryNavigationMessage({origin:'http://synthetic.local',source:frame.contentWindow,data,...extra});
send({type:'gallery-navigation',hidden:true},{origin:'http://untrusted.local'});
send({type:'gallery-navigation',hidden:true},{source:{}});
send({type:'gallery-navigation',hidden:'true'});
assert(!classes.has('gallery-nav-hidden'));assert.equal(acks.length,0);
send({type:'gallery-navigation',hidden:true});assert(classes.has('gallery-nav-hidden'));assert.equal(frame.style.height,'792px');
send({type:'gallery-navigation',hidden:false});assert(!classes.has('gallery-nav-hidden'));assert.equal(frame.style.height,'704px');
assert.equal(acks.at(-1).data.type,'gallery-navigation-state');assert.equal(acks.at(-1).data.hidden,false);
frame.hidden=true;const before=acks.length;send({type:'gallery-navigation',hidden:true});assert.equal(acks.length,before);assert(!classes.has('gallery-nav-hidden'));
console.log('Gallery navigation passed: down hides/up reveals, hysteresis, edge bounce, resize suppression, modal/inactive guards, iframe source/origin checks and viewport expansion.');
